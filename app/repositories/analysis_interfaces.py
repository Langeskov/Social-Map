"""Analysis persistence contracts: fact data is read-only for this layer."""
from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.domain.entities import AnalysisRun, AnalysisSource, AnalysisSourceSet


class AnalysisRunRepository(Protocol):
    def get(self, workspace_id: UUID, id: UUID) -> AnalysisRun | None: ...
    def list_by_workspace(self, workspace_id: UUID, *, target_type: str | None = None,
                          target_id: UUID | None = None, limit: int | None = None) -> list[AnalysisRun]: ...
    def save(self, entity: AnalysisRun) -> AnalysisRun: ...
    def update(self, entity: AnalysisRun) -> AnalysisRun: ...
    def delete(self, workspace_id: UUID, id: UUID) -> None: ...


class AnalysisSourceRepository(Protocol):
    def list_by_run(self, workspace_id: UUID, analysis_run_id: UUID) -> AnalysisSourceSet: ...
    def add_many(self, kind: str, workspace_id: UUID, analysis_run_id: UUID,
                 target_ids) -> tuple[AnalysisSource, ...]: ...
    def remove_for_run(self, workspace_id: UUID, analysis_run_id: UUID) -> None: ...
