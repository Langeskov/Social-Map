"""Event persistence contracts; Domain/stdlib only and caller-owned transactions."""
from datetime import datetime
from typing import Protocol
from uuid import UUID
from app.domain.entities import Event, EventParticipant


class EventRepository(Protocol):
    def get(self, workspace_id: UUID, id: UUID, *, include_deleted: bool = False) -> Event | None: ...
    def list_by_workspace(self, workspace_id: UUID, search: str = "", *, include_deleted: bool = False) -> list[Event]: ...
    def list_by_person(self, workspace_id: UUID, person_id: UUID, *, include_deleted: bool = False) -> list[Event]: ...
    def save(self, entity: Event) -> Event: ...
    def update(self, entity: Event) -> Event: ...
    def soft_delete(self, workspace_id: UUID, id: UUID, at: datetime) -> Event: ...
    def restore(self, workspace_id: UUID, id: UUID, at: datetime) -> Event: ...


class EventParticipantRepository(Protocol):
    def list_by_event(self, workspace_id: UUID, event_id: UUID) -> list[EventParticipant]: ...
    def list_by_person(self, workspace_id: UUID, person_id: UUID) -> list[EventParticipant]: ...
    def add(self, entity: EventParticipant) -> EventParticipant: ...
    def update_metadata(self, entity: EventParticipant) -> EventParticipant: ...
    def remove(self, workspace_id: UUID, event_id: UUID, person_id: UUID) -> None: ...
