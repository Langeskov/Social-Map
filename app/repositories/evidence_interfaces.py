"""Evidence persistence contracts; Domain/stdlib only and caller-owned transactions.

Deliberately absent: update_content, update_source, update_captured_at. Original
evidence material is create-only; correcting it means soft delete plus a new row.
"""
from datetime import datetime
from typing import Protocol
from uuid import UUID
from app.domain.entities import Evidence, EvidenceMedia


class EvidenceRepository(Protocol):
    def get(self, workspace_id: UUID, id: UUID, *, include_deleted: bool = False) -> Evidence | None: ...
    def list_by_event(self, workspace_id: UUID, event_id: UUID, *, include_deleted: bool = False,
                      kind: str | None = None) -> list[Evidence]: ...
    def list_by_workspace(self, workspace_id: UUID, *, include_deleted: bool = False,
                          kind: str | None = None) -> list[Evidence]: ...
    def save(self, entity: Evidence) -> Evidence: ...
    def update_metadata(self, entity: Evidence) -> Evidence: ...
    def soft_delete(self, workspace_id: UUID, id: UUID, at: datetime) -> Evidence: ...
    def restore(self, workspace_id: UUID, id: UUID, at: datetime) -> Evidence: ...


class EvidenceMediaRepository(Protocol):
    def get(self, workspace_id: UUID, id: UUID) -> EvidenceMedia | None: ...
    def list_by_evidence(self, workspace_id: UUID, evidence_id: UUID) -> list[EvidenceMedia]: ...
    def list_by_media(self, workspace_id: UUID, media_id: UUID) -> list[EvidenceMedia]: ...
    def add(self, entity: EvidenceMedia) -> EvidenceMedia: ...
    def remove(self, workspace_id: UUID, evidence_id: UUID, media_id: UUID,
               role: str | None = None) -> int: ...
