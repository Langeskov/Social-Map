"""Relationship persistence contracts: Domain/stdlib only, no transaction ownership."""
from datetime import datetime
from typing import Protocol
from uuid import UUID
from app.domain.entities import Relationship, RelationshipHistory

class RelationshipRepository(Protocol):
    def get(self, workspace_id: UUID, id: UUID, *, include_deleted: bool = False) -> Relationship | None: ...
    def get_by_identity(self, workspace_id: UUID, person_a_id: UUID, person_b_id: UUID,
                        relationship_type: str, directionality: str, *, include_deleted: bool = True) -> Relationship | None: ...
    def list_by_person(self, workspace_id: UUID, person_id: UUID, *, include_deleted: bool = False) -> list[Relationship]: ...
    def list_by_workspace(self, workspace_id: UUID, *, include_deleted: bool = False) -> list[Relationship]: ...
    def save(self, entity: Relationship) -> Relationship: ...
    def update(self, entity: Relationship) -> Relationship: ...
    def soft_delete(self, workspace_id: UUID, id: UUID, at: datetime) -> Relationship: ...

class RelationshipHistoryRepository(Protocol):
    def get(self, workspace_id: UUID, id: UUID) -> RelationshipHistory | None: ...
    def list_by_workspace(self, workspace_id: UUID) -> list[RelationshipHistory]: ...
    def list_by_event(self, workspace_id: UUID, event_id: UUID) -> list[RelationshipHistory]: ...
    def attach_event(self, workspace_id: UUID, id: UUID, event_id: UUID | None) -> RelationshipHistory: ...
    def list_by_relationship(self, workspace_id: UUID, relationship_id: UUID) -> list[RelationshipHistory]: ...
    def add(self, entity: RelationshipHistory) -> RelationshipHistory: ...
    def get_latest(self, workspace_id: UUID, relationship_id: UUID, *, as_of: datetime | None = None) -> RelationshipHistory | None: ...
