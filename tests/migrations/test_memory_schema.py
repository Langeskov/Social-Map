def expect_integrity(engine, code, callback):
    with pytest.raises(IntegrityError) as error:
        with engine.begin() as connection:
            callback(connection)
    assert error.value.orig.sqlite_errorname == "SQLITE_CONSTRAINT_" + code


def table_rows(engine, names):
    """Canonical rows of ``names``, keyed by table name."""
    snapshot = {}
    with engine.connect() as connection:
        for name in sorted(names):
            table = sa.Table(name, sa.MetaData(), autoload_with=connection)
            rows = connection.execute(sa.select(table).order_by(table.c.id)).all()
            # Driver values (UUID, datetime) are coerced to stable text so the
            # comparison never depends on reflected Python type identity.
            snapshot[name] = [tuple(str(value) for value in row) for row in rows]
    return snapshot


def table_schema(engine, names):
    """Every named constraint and index of ``names``, normalized to plain data."""
    snapshot = {}
    with engine.connect() as connection:
        inspector = sa.inspect(connection)
        for name in sorted(names):
            snapshot[name] = (
                [dict(column) for column in inspector.get_columns(name)],
                inspector.get_pk_constraint(name), inspector.get_check_constraints(name),
                inspector.get_unique_constraints(name), inspector.get_foreign_keys(name),
                inspector.get_indexes(name),
            )
    # Reflection allocates fresh type and SQL-expression objects on every call;
    # their representations are normalized to strings, exactly like the Phase 6
    # evidence, Phase 7 projection and Phase 8 analysis snapshots.
    for schema in snapshot.values():
        for column in schema[0]:
            column["type"] = str(column["type"])
        for index in schema[5]:
            index["dialect_options"] = {
                key: str(value) if isinstance(value, sa.sql.elements.ClauseElement) else value
                for key, value in index.get("dialect_options", {}).items()
            }
    return snapshot


def fact_state(engine):
    return table_rows(engine, FACT_TABLES), table_schema(engine, FACT_TABLES)


def analysis_state(engine):
    return table_rows(engine, ANALYSIS_TABLES), table_schema(engine, ANALYSIS_TABLES)


def raw_table_names(engine):
    with engine.connect() as connection:
        return {row[0] for row in connection.exec_driver_sql(
            "SELECT name FROM sqlite_master WHERE type = 'table'")}


def sqlite_master_names(engine):
    with engine.connect() as connection:
        return {row[0] for row in connection.exec_driver_sql("SELECT name FROM sqlite_master")}


def master_snapshot(engine):
    """Every sqlite_master object with its kind and DDL, ignoring FTS5 internals.

    The FTS5 shadow tables carry engine-managed bookkeeping rows and a
    non-deterministic ``_idx`` blob, so the Phase 7 projection is compared through
    ``projection_objects()`` instead of through this raw snapshot.
    """
    with engine.connect() as connection:
        rows = connection.exec_driver_sql(
            "SELECT type, name, tbl_name, sql FROM sqlite_master ORDER BY type, name").all()
    return [tuple(row) for row in rows if not str(row[1]).startswith(SEARCH_DOCUMENT_FTS)]


def projection_objects(engine):
    """Projection objects actually present, including the FTS5 shadow tables."""
    return (PROJECTION_OBJECTS & sqlite_master_names(engine)
            | fts_shadow_tables(raw_table_names(engine)))


def analysis_objects(engine):
    """Every sqlite_master object whose name belongs to the Phase 8 analysis ledger.

    Both the five tables and the seven indexes created by 0007 carry an ``analysis``
    prefix; SQLite's own ``sqlite_autoindex_...`` objects do not.
    """
    return {name for name in sqlite_master_names(engine) if name.startswith("analysis")}


def autoindex_objects(engine):
    """SQLite's own index for UNIQUE(workspace_id, id); its name is engine-generated."""
    return {name for name in sqlite_master_names(engine)
            if name.startswith("sqlite_autoindex_" + MEMORY + "_")}


def memory_objects(engine):
    """Every object 0008 owns, matched exactly instead of by a %memory% substring.

    The set is the table, its five named indexes and SQLite's auto-index for
    UNIQUE(workspace_id, id). ``like_memory_names`` proves separately that a naive
    substring search over sqlite_master finds nothing else either.
    """
    return (sqlite_master_names(engine) & MEMORY_OBJECTS) | autoindex_objects(engine)


def like_memory_names(engine):
    """Every sqlite_master name containing "memory", as a raw LIKE search sees it."""
    with engine.connect() as connection:
        return {row[0] for row in connection.exec_driver_sql(
            "SELECT name FROM sqlite_master WHERE name LIKE '%memory%'")}


def fact_table_names(engine):
    """Only the business fact tables: every later group is filtered out."""
    names = set(sa.inspect(engine).get_table_names()) - {"alembic_version"}
    return (names - PROJECTION_OBJECTS - fts_shadow_tables(names) - ANALYSIS_TABLES
            - MEMORY_TABLES)


def assert_schema_matches_orm(engine, names):
    """The migrated schema of ``names`` matches the frozen ORM metadata exactly."""
    Base.metadata.tables  # Metadata is registered by the caller's model import.
    inspector = sa.inspect(engine)
    for name in sorted(names):
        table = Base.metadata.tables[name]
        assert {column["name"] for column in inspector.get_columns(name)} == set(table.c.keys())
        assert {column["name"]: column["nullable"]
                for column in inspector.get_columns(name)} == {
            column.name: column.nullable for column in table.columns}
        assert inspector.get_pk_constraint(name)["name"] == table.primary_key.name
        for kind, reflected in [(sa.CheckConstraint, inspector.get_check_constraints(name)),
                                (sa.ForeignKeyConstraint, inspector.get_foreign_keys(name)),
                                (sa.UniqueConstraint, inspector.get_unique_constraints(name))]:
            assert {item["name"] for item in reflected} == {
                item.name for item in table.constraints if isinstance(item, kind)}
        assert {index["name"]: tuple(index["column_names"])
                for index in inspector.get_indexes(name)} == {
            index.name: tuple(column.name for column in index.columns)
            for index in table.indexes}


def assert_frozen_members_and_options(inspector):
    """The unique constraint covers only (workspace_id, id) and FKs never cascade."""
    assert inspector.get_unique_constraints(MEMORY) == [
        {"name": "uq_memory_workspace_id_id", "column_names": ["workspace_id", "id"]}]
    assert {tuple(unique["column_names"])
            for unique in inspector.get_unique_constraints(MEMORY)} == {("workspace_id", "id")}
    # No ON DELETE clause anywhere: NO ACTION, so a referenced person or run is
    # blocked instead of silently taking the memory with it.
    assert {fk["name"]: (tuple(fk["constrained_columns"]), fk["referred_table"],
                         tuple(fk["referred_columns"]))
            for fk in inspector.get_foreign_keys(MEMORY)} == FOREIGN_KEYS
    assert all(fk["options"] == {} for fk in inspector.get_foreign_keys(MEMORY))


def test_0007_to_0008_adds_only_the_memory_table_and_keeps_every_fact_table(tmp_path, monkeypatch):
    engine, migration = open_database(tmp_path, monkeypatch)
    try:
        migrate(engine, migration, "0007_analysis")
        with engine.begin() as connection:
            facts = seed_facts(connection)
            seed_analysis(connection, facts)
        fact_before = fact_state(engine)
        analysis_before = analysis_state(engine)
        projection_before = projection_objects(engine)
        assert current_heads(engine) == ("0007_analysis",)
        assert memory_objects(engine) == set()
        assert like_memory_names(engine) == set()
        assert fact_table_names(engine) == FACT_TABLES

        migrate(engine, migration, "0008_memory")
        assert current_heads(engine) == ("0008_memory",)
        # The eleven business fact tables keep their rows and their whole schema.
        assert fact_table_names(engine) == FACT_TABLES
        assert len(fact_table_names(engine)) == 11
        assert fact_state(engine) == fact_before
        # The Phase 8 analysis ledger keeps all five of its tables, untouched.
        assert analysis_objects(engine) == ANALYSIS_TABLES
        assert analysis_state(engine) == analysis_before
        # So does the Phase 7 projection, including the FTS5 index.
        assert projection_objects(engine) == (
            projection_before | fts_shadow_tables(raw_table_names(engine)))
        # Memory is a fourth group: never a fact table, projection or analysis object.
        assert MEMORY_TABLES.isdisjoint(FACT_TABLES)
        assert MEMORY_TABLES.isdisjoint(PROJECTION_TABLES)
        assert MEMORY_TABLES.isdisjoint(ANALYSIS_TABLES)
        assert raw_table_names(engine) & MEMORY_TABLES == MEMORY_TABLES
        # The complete schema is the fact tables plus the projection objects (the
        # FTS5 virtual table and the five shadow tables SQLite creates for it) plus
        # the five analysis tables plus memory.
        assert set(sa.inspect(engine).get_table_names()) == expected_head_tables(
            raw_table_names(engine))
        # Every object 0008 created is present, and no other name contains "memory".
        assert memory_objects(engine) == MEMORY_OBJECTS | autoindex_objects(engine)
        # SQLite materializes two automatic indexes: one for PRIMARY KEY (id), which
        # is not an INTEGER key, and one for UNIQUE(workspace_id, id).
        assert len(autoindex_objects(engine)) == 2
        assert like_memory_names(engine) == memory_objects(engine)
        assert_schema_matches_orm(engine, FACT_TABLES | ANALYSIS_TABLES | MEMORY_TABLES)

        inspector = sa.inspect(engine)
        table = MemoryModel.__table__
        assert table.primary_key.name == "pk_memory"
        assert inspector.get_pk_constraint(MEMORY) == {
            "constrained_columns": ["id"], "name": "pk_memory"}
        assert [column["name"] for column in inspector.get_columns(MEMORY)] == [
            "id", "workspace_id", "person_id", "kind", "content", "source_type",
            "source_analysis_id", "confirmed_at", "valid_from", "valid_until",
            "created_at", "updated_at", "deleted_at"]
        assert {column["name"]: column["nullable"]
                for column in inspector.get_columns(MEMORY)} == {
            "id": False, "workspace_id": False, "person_id": True, "kind": False,
            "content": False, "source_type": False, "source_analysis_id": True,
            # A memory exists only once the user confirmed it.
            "confirmed_at": False, "valid_from": True, "valid_until": True,
            "created_at": False, "updated_at": False, "deleted_at": True}
        assert {check["name"] for check in inspector.get_check_constraints(MEMORY)} == CHECK_NAMES
        assert_frozen_members_and_options(inspector)
        assert {index["name"]: tuple(index["column_names"])
                for index in inspector.get_indexes(MEMORY)} == MEMORY_INDEXES
        # No index carries uniqueness: neither person_id nor content is unique.
        assert not any(index["unique"] for index in inspector.get_indexes(MEMORY))
        assert {tuple(column.name for column in constraint.columns)
                for constraint in table.constraints
                if isinstance(constraint, sa.UniqueConstraint)} == {("workspace_id", "id")}

        # A fresh process must reflect the same memory table from disk.
        head_tables = set(sa.inspect(engine).get_table_names())
        objects = memory_objects(engine)
        engine.dispose()
        reopened = create_sqlite_engine(AppConfig(data_dir=tmp_path / "phase9 memory 数据库"))
        try:
            assert current_heads(reopened) == ("0008_memory",)
            assert fact_state(reopened) == fact_before
            assert analysis_state(reopened) == analysis_before
            assert fact_table_names(reopened) == FACT_TABLES
            assert analysis_objects(reopened) == ANALYSIS_TABLES
            assert set(sa.inspect(reopened).get_table_names()) == head_tables
            assert memory_objects(reopened) == objects
            assert like_memory_names(reopened) == objects
            assert_schema_matches_orm(reopened, FACT_TABLES | ANALYSIS_TABLES | MEMORY_TABLES)
            assert_frozen_members_and_options(sa.inspect(reopened))
        finally:
            reopened.dispose()
    finally:
        engine.dispose()


def test_0008_to_0007_drops_only_the_memory_table_and_keeps_every_fact_and_analysis_row(
        tmp_path, monkeypatch):
    engine, migration = open_database(tmp_path, monkeypatch)
    try:
        migrate(engine, migration, "0007_analysis")
        with engine.begin() as connection:
            facts = seed_facts(connection)
            run = seed_analysis(connection, facts)
        fact_before = fact_state(engine)
        analysis_before = analysis_state(engine)
        projection_before = projection_objects(engine)
        master_before = master_snapshot(engine)
        assert memory_objects(engine) == set()

        migrate(engine, migration, "0008_memory")
        with engine.begin() as connection:
            add_memory(connection, facts["scope"], person_id=facts["person_a"],
                       kind="PREFERENCE", content="保留记忆")
            add_memory(connection, facts["scope"], source_type="ANALYSIS",
                       source_analysis_id=run, kind="CONTEXT", content="来自分析的记忆")
        assert memory_objects(engine) == MEMORY_OBJECTS | autoindex_objects(engine)
        with engine.connect() as connection:
            assert connection.scalar(sa.select(sa.func.count()).select_from(MemoryModel)) == 2

        migrate(engine, migration, "0007_analysis", down=True)
        assert current_heads(engine) == ("0007_analysis",)
        # Not one object 0008 created is left, in any form: the table, its five
        # named indexes and SQLite's auto-index for the UNIQUE constraint all go.
        assert memory_objects(engine) == set()
        assert like_memory_names(engine) == set()
        assert raw_table_names(engine) & MEMORY_TABLES == set()
        assert sa.inspect(engine).has_table(MEMORY) is False
        with pytest.raises(sa.exc.NoSuchTableError):
            sa.inspect(engine).get_indexes(MEMORY)
        # Every non-FTS5 sqlite_master row (table, index or anything else) is
        # byte-identical to the pre-migration snapshot: no residual object.
        assert master_snapshot(engine) == master_before
        # The eleven fact tables and the five analysis tables keep every row and
        # their whole named schema.
        assert fact_table_names(engine) == FACT_TABLES
        assert analysis_objects(engine) == ANALYSIS_TABLES
        assert fact_state(engine) == fact_before
        assert analysis_state(engine) == analysis_before
        assert projection_objects(engine) == projection_before
        assert set(sa.inspect(engine).get_table_names()) == (
            FACT_TABLES | PROJECTION_OBJECTS | ANALYSIS_TABLES
            | fts_shadow_tables(raw_table_names(engine)) | {"alembic_version"})
        with engine.connect() as connection:
            assert connection.exec_driver_sql("PRAGMA foreign_keys").scalar() == 1
            assert connection.exec_driver_sql("PRAGMA foreign_key_check").all() == []
    finally:
        engine.dispose()


def test_0007_0008_0007_0008_roundtrip_keeps_facts_and_leaves_memory_empty(tmp_path, monkeypatch):
    engine, migration = open_database(tmp_path, monkeypatch)
    try:
        migrate(engine, migration, "0007_analysis")
        with engine.begin() as connection:
            facts = seed_facts(connection)
            seed_analysis(connection, facts)
        fact_before = fact_state(engine)
        analysis_before = analysis_state(engine)
        for revision, down in [("0008_memory", False), ("0007_analysis", True),
                               ("0008_memory", False)]:
            migrate(engine, migration, revision, down=down)
            assert current_heads(engine) == (revision,)
            # Fact and analysis rows and schemas are identical in every segment of
            # the roundtrip: 0007 -> 0008 -> 0007 -> 0008.
            assert table_rows(engine, FACT_TABLES) == fact_before[0]
            assert table_schema(engine, FACT_TABLES) == fact_before[1]
            assert table_rows(engine, ANALYSIS_TABLES) == analysis_before[0]
            assert table_schema(engine, ANALYSIS_TABLES) == analysis_before[1]
            assert fact_table_names(engine) == FACT_TABLES
            assert analysis_objects(engine) == ANALYSIS_TABLES
            assert_schema_matches_orm(engine, FACT_TABLES | ANALYSIS_TABLES)
            with engine.connect() as connection:
                assert connection.exec_driver_sql("PRAGMA foreign_keys").scalar() == 1
                assert connection.exec_driver_sql("PRAGMA foreign_key_check").all() == []
            if down:
                assert memory_objects(engine) == set()
                assert like_memory_names(engine) == set()
            else:
                assert memory_objects(engine) == MEMORY_OBJECTS | autoindex_objects(engine)
                # The migration seeds nothing: the memory table starts empty.
                with engine.connect() as connection:
                    assert connection.scalar(
                        sa.select(sa.func.count()).select_from(MemoryModel)) == 0
        assert current_heads(engine) == ("0008_memory",)
        assert table_rows(engine, FACT_TABLES) == fact_before[0]
        assert table_schema(engine, ANALYSIS_TABLES) == analysis_before[1]
    finally:
        engine.dispose()


