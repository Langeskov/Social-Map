def test_deleting_a_referenced_person_run_or_workspace_is_blocked_without_cascade(
        tmp_path, monkeypatch):
    engine, migration = open_database(tmp_path, monkeypatch)
    try:
        migrate(engine, migration, "head")
        with engine.begin() as connection:
            facts = seed_facts(connection)
            seed_analysis(connection, facts)
        fact_before = fact_state(engine)
        scope = facts["scope"]
        # One person, one run and one workspace whose ONLY reference is a memory, so
        # the block below is attributable to the memory row and not to another table.
        with engine.begin() as connection:
            only_memory_person = uuid4()
            insert(connection, PersonModel, id=only_memory_person, workspace_id=scope,
                   display_name="仅被记忆引用", real_name=None, notes=None,
                   created_at=NOW, updated_at=NOW)
            only_memory_run = add_run(connection, scope)["id"]
            plain = uuid4()
            insert(connection, WorkspaceModel, id=plain, name=str(plain), description=None,
                   created_at=NOW, updated_at=NOW)
            person_memory = add_memory(connection, scope, person_id=only_memory_person,
                                       content="人物记忆")["id"]
            run_memory = add_memory(connection, scope, source_type="ANALYSIS",
                                    source_analysis_id=only_memory_run,
                                    content="分析记忆")["id"]
            workspace_memory = add_memory(connection, plain, person_id=None,
                                          content="工作区级记忆")["id"]
        with engine.connect() as connection:
            assert connection.scalar(sa.select(sa.func.count()).select_from(MemoryModel)) == 3

        # The three foreign keys carry no ON DELETE clause (asserted above), so the
        # database - not only the application - refuses each parent delete.
        expect_integrity(engine, "FOREIGNKEY", lambda c: c.exec_driver_sql(
            "DELETE FROM person WHERE id = ?", (only_memory_person.hex,)))
        expect_integrity(engine, "FOREIGNKEY", lambda c: c.exec_driver_sql(
            "DELETE FROM analysis_run WHERE id = ?", (only_memory_run.hex,)))
        expect_integrity(engine, "FOREIGNKEY", lambda c: c.exec_driver_sql(
            "DELETE FROM workspace WHERE id = ?", (plain.hex,)))
        with engine.connect() as connection:
            assert connection.scalar(sa.select(sa.func.count()).select_from(PersonModel).where(
                PersonModel.id == only_memory_person)) == 1
            assert connection.scalar(sa.select(sa.func.count()).select_from(
                AnalysisRunModel).where(AnalysisRunModel.id == only_memory_run)) == 1
            assert connection.scalar(sa.select(sa.func.count()).select_from(
                WorkspaceModel).where(WorkspaceModel.id == plain)) == 1
            assert connection.scalar(sa.select(sa.func.count()).select_from(MemoryModel)) == 3

        # The block comes from the referencing row, not from the table: once that one
        # memory row is gone, the very same deletes succeed. No cascade ever ran.
        with engine.begin() as connection:
            connection.exec_driver_sql("DELETE FROM memory WHERE id = ?", (person_memory.hex,))
            connection.exec_driver_sql("DELETE FROM person WHERE id = ?",
                                       (only_memory_person.hex,))
            connection.exec_driver_sql("DELETE FROM memory WHERE id = ?", (run_memory.hex,))
            connection.exec_driver_sql("DELETE FROM analysis_run WHERE id = ?",
                                       (only_memory_run.hex,))
            connection.exec_driver_sql("DELETE FROM memory WHERE id = ?", (workspace_memory.hex,))
            connection.exec_driver_sql("DELETE FROM workspace WHERE id = ?", (plain.hex,))
        with engine.connect() as connection:
            assert connection.scalar(sa.select(sa.func.count()).select_from(MemoryModel)) == 0
            assert connection.exec_driver_sql("PRAGMA foreign_keys").scalar() == 1
            assert connection.exec_driver_sql("PRAGMA foreign_key_check").all() == []
        # Deleting a memory never rewrites a fact or an analysis row.
        assert fact_state(engine) == fact_before
    finally:
        engine.dispose()


