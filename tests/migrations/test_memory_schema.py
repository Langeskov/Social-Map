def test_offline_sql_renders_the_memory_ddl_and_executes_on_real_sqlite(tmp_path, monkeypatch):
    engine, migration = open_database(tmp_path, monkeypatch)

    def offline_script(revision, *, down=False):
        output = StringIO()
        migration.output_buffer = output
        (command.downgrade if down else command.upgrade)(migration, revision, sql=True)
        return output.getvalue()

    def execute_script(sql):
        connection = engine.raw_connection()
        try:
            assert connection.execute("PRAGMA foreign_keys").fetchone()[0] == 1
            connection.executescript(sql)
        finally:
            connection.close()

    try:
        upgrade_sql = offline_script("0007_analysis:0008_memory")
        # Offline rendering never connects to or creates a database file.
        assert sa.inspect(engine).get_table_names() == []
        assert f"CREATE TABLE {MEMORY} " in upgrade_sql
        assert "CONSTRAINT pk_memory PRIMARY KEY (id)" in upgrade_sql
        assert "CONSTRAINT fk_memory_workspace_person FOREIGN KEY" \
               "(workspace_id, person_id) REFERENCES person (workspace_id, id)" in upgrade_sql
        assert "CONSTRAINT fk_memory_workspace_analysis_run FOREIGN KEY" \
               "(workspace_id, source_analysis_id) REFERENCES analysis_run " \
               "(workspace_id, id)" in upgrade_sql
        assert "CONSTRAINT fk_memory_workspace_id_workspace FOREIGN KEY(workspace_id) " \
               "REFERENCES workspace (id)" in upgrade_sql
        assert "CONSTRAINT uq_memory_workspace_id_id UNIQUE (workspace_id, id)" in upgrade_sql
        assert "CONSTRAINT ck_memory_kind_valid CHECK " \
               "(kind IN ('FACT','PREFERENCE','CONTEXT'))" in upgrade_sql
        assert "CONSTRAINT ck_memory_content_normalized CHECK " \
               f"({CONTENT_CHECK})" in upgrade_sql
        assert "CONSTRAINT ck_memory_source_type_valid CHECK " \
               "(source_type IN ('MANUAL','ANALYSIS'))" in upgrade_sql
        assert "CONSTRAINT ck_memory_source_reference_valid CHECK " \
               f"({SOURCE_REFERENCE_CHECK})" in upgrade_sql
        assert "CONSTRAINT ck_memory_validity_window_valid CHECK " \
               f"({VALIDITY_CHECK})" in upgrade_sql
        for name in sorted(MEMORY_INDEXES):
            assert f"CREATE INDEX {name} ON memory " in upgrade_sql
        # No unique constraint ever covered person_id or content.
        assert "UNIQUE (person_id)" not in upgrade_sql
        assert "UNIQUE (content)" not in upgrade_sql

        # The whole chain is rendered from base, so the offline script is a clean
        # install; executing it produces exactly the head schema.
        head_sql = offline_script("head")
        assert f"CREATE TABLE {MEMORY} " in head_sql
        for name in sorted(MEMORY_INDEXES):
            assert f"CREATE INDEX {name} ON memory " in head_sql
        execute_script(head_sql)
        assert current_heads(engine) == ("0008_memory",)
        assert memory_objects(engine) == MEMORY_OBJECTS | autoindex_objects(engine)
        assert fact_table_names(engine) == FACT_TABLES
        assert analysis_objects(engine) == ANALYSIS_TABLES
        assert set(sa.inspect(engine).get_table_names()) == expected_head_tables(
            raw_table_names(engine))
        with engine.begin() as connection:
            facts = seed_facts(connection)
            run = seed_analysis(connection, facts)
            add_memory(connection, facts["scope"], person_id=facts["person_a"],
                       content="离线脚本记忆")
            add_memory(connection, facts["scope"], source_type="ANALYSIS",
                       source_analysis_id=run, content="离线脚本分析记忆")
        fact_before = fact_state(engine)
        analysis_before = analysis_state(engine)

        downgrade_sql = offline_script("0008_memory:0007_analysis", down=True)
        for name in sorted(MEMORY_INDEXES):
            assert f"DROP INDEX {name}" in downgrade_sql
        assert f"DROP TABLE {MEMORY}" in downgrade_sql
        # Every index is dropped before the table it belongs to.
        assert downgrade_sql.index(f"DROP TABLE {MEMORY}") > max(
            downgrade_sql.index(f"DROP INDEX {name}") for name in MEMORY_INDEXES)
        assert "DROP TABLE analysis_run" not in downgrade_sql
        execute_script(downgrade_sql)
        assert current_heads(engine) == ("0007_analysis",)
        assert memory_objects(engine) == set()
        assert like_memory_names(engine) == set()
        assert fact_table_names(engine) == FACT_TABLES
        assert analysis_objects(engine) == ANALYSIS_TABLES
        assert fact_state(engine) == fact_before
        assert analysis_state(engine) == analysis_before

        reupgrade_sql = offline_script("0007_analysis:0008_memory")
        assert f"CREATE TABLE {MEMORY} " in reupgrade_sql
        execute_script(reupgrade_sql)
        assert current_heads(engine) == ("0008_memory",)
        assert memory_objects(engine) == MEMORY_OBJECTS | autoindex_objects(engine)
        assert fact_state(engine) == fact_before
        assert analysis_state(engine) == analysis_before
        with engine.connect() as connection:
            # The migration seeds nothing: the re-created table starts empty.
            assert connection.scalar(sa.select(sa.func.count()).select_from(MemoryModel)) == 0
            assert connection.exec_driver_sql("PRAGMA foreign_key_check").all() == []
    finally:
        engine.dispose()


